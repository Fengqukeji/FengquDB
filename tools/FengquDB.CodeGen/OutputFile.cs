using System.Text;
using FengquDB.Generators;

namespace FengquDB.CodeGen;

// A single deterministic file makes publication atomic and removes stale entity
// declarations automatically when a source type is renamed or deleted.
internal static class OutputFile {
    internal const string Name = "FengquDB.Entities.g.cs";
    const string Marker = "// Generated by fqdb-codegen. Changes are overwritten.\n";
    internal static string Render(IEnumerable<string> sources) {
        var output = new StringBuilder(Marker);
        output.AppendLine("// <auto-generated/>");
        output.Append("#if ").Append(EntityGenerator.ManualSymbol).Append(" && !").AppendLine(EntityGenerator.ForceSymbol);
        output.AppendLine("#nullable enable\nusing System;");
        foreach (string source in sources) {
            foreach (string line in source.Replace("\r\n", "\n").Split('\n')) {
                if (line is "// <auto-generated/>" or "#nullable enable" or "using System;" or "") continue;
                output.AppendLine(line);
            }
        }
        output.AppendLine("#endif");
        return output.ToString().Replace("\r\n", "\n");
    }
    internal static async Task<bool> PublishAsync(string path, string content, bool check, CancellationToken token) {
        if (File.Exists(path)) {
            string current = await File.ReadAllTextAsync(path, token);
            if (current == content) return false;
            if (!current.StartsWith(Marker, StringComparison.Ordinal) &&
                !current.StartsWith(Marker.Replace("\n", "\r\n"), StringComparison.Ordinal))
                throw new IOException("Output file is not owned by fqdb-codegen. Choose another output directory.");
        }
        if (check) return true;
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        string temporary = Path.Combine(Path.GetDirectoryName(path)!, ".fqdb-" + Guid.NewGuid().ToString("N") + ".tmp");
        try {
            await File.WriteAllTextAsync(temporary, content, new UTF8Encoding(false), token);
            token.ThrowIfCancellationRequested();
            File.Move(temporary, path, overwrite: true);
        } finally {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
        return true;
    }
}
