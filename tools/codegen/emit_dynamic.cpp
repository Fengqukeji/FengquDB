void emit_python(const Model &m, Files &files) {
    std::ostringstream o;
    o << "# Generated by FengquDB native codegen v1. DO NOT EDIT.\n" << runtime_python << "\n";
    for (const auto &e : m.entities) {
        o << "\n@dataclass\nclass " << e.name << ":\n";
        for (const auto &f : e.fields) {
            auto t = f.type == "string" ? "str" : f.type == "bytes" ? "bytes" : f.type == "bool" ? "bool" : (wire(f) == 1 || wire(f) == 5) ? "float" : "int";
            auto d = f.type == "string" ? "''" : f.type == "bytes" ? "b''" : f.type == "bool" ? "False" : "0";
            o << "    " << f.name << ": " << t << " = " << d << "\n";
        }
        o << "    fq_unknown: bytes = field(default=b'', init=False, repr=False, compare=False)\n"
          << "    def fq_encode_into(self, out):\n        start = len(out)\n";
        for (const auto &f : e.fields) {
            auto v = "self." + f.name;
            o << "        _fq_u(out, " << tag(f) << ")\n";
            if (text(f)) o << "        if len(" << v << ") > _FQ_LIMIT: raise ValueError('Entity exceeds 16 MiB')\n"
                          << "        _fq_b(out, " << (f.type == "string" ? v + ".encode('utf-8')" : v) << ", start)\n";
            else if (wire(f) == 0) {
                if (f.type == "bool") o << "        _fq_u(out, _fq_bool(" << v << "))\n";
                else {
                    o << "        v = _fq_int(" << v << ", " << (f.type.find("32") != std::string::npos ? 32 : 64) << ", " << (signed_int(f) ? "True" : "False") << ")\n"
                      << "        _fq_u(out, " << (signed_int(f) ? "(v << 1) ^ (v >> 63)" : "v") << ")\n";
                }
            } else o << "        out.extend(_struct.pack('" << (f.type == "float" ? "<f" : "<d") << "', " << v << "))\n";
        }
        o << "        _fq_room(out, start, len(self.fq_unknown))\n        out.extend(self.fq_unknown)\n        if len(out) - start > _FQ_LIMIT: raise ValueError('Entity exceeds 16 MiB')\n        return out\n"
          << "    def fq_encode(self):\n        return bytes(self.fq_encode_into(bytearray()))\n"
          << "    @staticmethod\n    def fq_decode(data):\n        r = _FqReader(data)\n        out = " << e.name << "()\n        unknown = bytearray()\n"
          << "        while r.pos < len(r.data):\n            begin = r.pos\n            t = r.tag()\n";
        bool first = true;
        for (const auto &f : e.fields) {
            o << "            " << (first ? "if" : "elif") << " t == " << tag(f) << ": out." << f.name << " = "; first = false;
            if (text(f)) o << "bytes(r.b())" << (f.type == "string" ? ".decode('utf-8')" : "");
            else if (f.type == "bool") o << "_fq_read_bool(r.u())";
            else if (signed_int(f)) o << "_fq_signed(r.u(), " << (f.type == "sint32" ? 32 : 64) << ")";
            else if (wire(f) == 0) o << "_fq_int(r.u(), " << (f.type == "uint32" ? 32 : 64) << ")";
            else o << "r.floating('" << (f.type == "float" ? "<f', 4" : "<d', 8") << ")";
            o << "\n";
        }
        o << "            else:\n                r.skip(t)\n                unknown.extend(r.data[begin:r.pos])\n"
          << "        out.fq_unknown = bytes(unknown)\n        return out\n    def fq_key(self):\n";
        const auto &k = key(e);
        if (k.type != "string") o << "        _fq_int(self." << k.name << ", " << (k.type.find("32") != std::string::npos ? 32 : 64) << ", " << (signed_int(k) ? "True" : "False") << ")\n";
        o << "        return _fq_key(" << quote(e.prefix) << ".encode('utf-8'), self." << k.name << ")\n";
    }
    files["python/fq_models.py"] = o.str();
}
void emit_node(const Model &m, Files &files) {
    std::ostringstream o, d;
    o << banner << "'use strict';\n" << runtime_node << "\n";
    d << banner;
    for (const auto &e : m.entities) {
        o << "\nclass " << e.name << " {\n  constructor() {\n";
        d << "export class " << e.name << " {\n";
        for (const auto &f : e.fields) {
            auto def = f.type == "string" ? "''" : f.type == "bytes" ? "new Uint8Array(0)" : f.type == "bool" ? "false" : f.type.find("64") != std::string::npos ? "0n" : "0";
            o << "    this." << f.name << "=" << def << ";\n";
            d << "  " << f.name << ": " << (f.type == "string" ? "string" : f.type == "bytes" ? "Uint8Array" : f.type == "bool" ? "boolean" : f.type.find("64") != std::string::npos ? "bigint" : "number") << ";\n";
        }
        o << "    this.fqUnknown=new Uint8Array(0);\n  }\n  fqEncode(destination) {\n    const w=new _FqWriter(destination);\n";
        for (const auto &f : e.fields) {
            auto v = "this." + f.name;
            o << "    w.u(" << tag(f) << ");\n";
            if (text(f)) o << "    w.b(" << (f.type == "string" ? "_fqText(" + v + ")" : v) << ");\n";
            else if (wire(f) == 0) {
                if (f.type == "bool") o << "    if(typeof " << v << "!=='boolean')throw new TypeError('Expected bool'); w.u(" << v << "?1:0);\n";
                else {
                    o << "    {const x=_fqInt(" << v << "," << (f.type.find("32") != std::string::npos ? 32 : 64) << "," << (signed_int(f) ? "true" : "false") << ");w.u(" << (signed_int(f) ? "(x<<1n)^(x>>63n)" : "x") << ");}\n";
                }
            } else o << "    if(typeof " << v << "!=='number')throw new TypeError('Expected number'); w.f(" << v << "," << (f.type == "float" ? 4 : 8) << ");\n";
        }
        o << "    w.raw(this.fqUnknown); return w.finish();\n  }\n  fqEncodeInto(destination) {return this.fqEncode(destination).length;}\n"
          << "  static fqDecode(data) {\n    const r=new _FqReader(data),out=new " << e.name << "(),unknown=[];\n"
          << "    while(r.pos<r.data.length){const begin=r.pos,t=r.tag();switch(t){\n";
        for (const auto &f : e.fields) {
            o << "      case " << tag(f) << ":out." << f.name << "=";
            if (f.type == "string") o << "_fqDecoder.decode(r.b())";
            else if (f.type == "bytes") o << "Buffer.from(r.b())";
            else if (f.type == "bool") o << "_fqBool(r.u())";
            else if (wire(f) == 0) o << (signed_int(f) ? "_fqSigned" : "_fqUnsigned") << "(r.u()," << (f.type.find("32") != std::string::npos ? 32 : 64) << ")";
            else o << "r.f(" << (f.type == "float" ? 4 : 8) << ")";
            o << ";break;\n";
        }
        o << "      default:r.skip(t);unknown.push(r.data.subarray(begin,r.pos));break;\n    }}\n    if(unknown.length)out.fqUnknown=Buffer.concat(unknown);return out;\n  }\n"
          << "  fqKey() {\n";
        const auto &k = key(e);
        if (k.type != "string") o << "    _fqInt(this." << k.name << "," << (k.type.find("32") != std::string::npos ? 32 : 64) << "," << (signed_int(k) ? "true" : "false") << ");\n";
        o << "    return _fqKey(Buffer.from(" << quote(e.prefix) << ",'utf8'),this." << k.name << ");\n  }\n}\nexports." << e.name << "=" << e.name << ";\n";
        d << "  fqUnknown: Uint8Array;\n  fqEncode(destination?: Uint8Array): Uint8Array;\n  fqEncodeInto(destination: Uint8Array): number;\n  static fqDecode(data: Uint8Array): " << e.name << ";\n  fqKey(): Uint8Array;\n}\n";
    }
    files["node/fq_models.js"] = o.str(); files["node/fq_models.d.ts"] = d.str();
}
